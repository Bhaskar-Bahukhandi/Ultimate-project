def iteration_days(round_name, ranks):
    days = [D(f"{round_name}: choose the fixes from the funnel report",
              [f"Read the {round_name} funnel report and rank drop-off points by players lost",
               "For each of the top items write a hypothesis, the change, and the metric that should move",
               "Agree the list with the user; design changes that touch combat, story progression or saves need explicit approval",
               "Tag each item with the build version it will ship in"],
              f"{round_name} change list agreed with a target metric per item")]
    for i, (area, change, metric) in enumerate(ranks, 1):
        days.append(D(f"{round_name} item {i}: {area}",
                      [f"Reproduce the problem at '{area}' with the telemetry seed or a playtest save",
                       f"Change: {change}",
                       "Add or update a test that locks the new behaviour",
                       f"Instrument the metric: {metric}",
                       "Run the bot route through the area on Beginner and Hell"],
                      f"{area} change merged with its metric instrumented"))
    days.append(D(f"{round_name}: ship the iteration build and verify",
                  ["Export with `export_windows.ps1 -Demo`, run the tour and the nightly bot",
                   "Check saves from the previous demo version load",
                   "Push to itch and the Steam demo private branch; the user makes it public",
                   "Write patch notes with `/patch-notes`"],
                  f"{round_name} build live; old saves load"))
    return days


