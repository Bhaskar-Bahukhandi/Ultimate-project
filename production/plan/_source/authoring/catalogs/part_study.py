def build():
    out = []
    for domain, (default_key, lines) in DOMAINS.items():
        for line in lines:
            parts = [p.strip() for p in line.split("||")]
            topic, exercise = parts[0], parts[1]
            key = parts[2] if len(parts) > 2 and parts[2] else (default_key or "none")
            if key.startswith("gd:"):
                res = gd(key[3:])
            else:
                res = R[key]
            out.append({"domain": domain, "topic": topic, "exercise": exercise, "resource": res})
    return out
